/**
 * Generates self-contained script folders for polybar and i3status-rust:
 *
 *   <bar>/scripts/now-playing.ts, pomodoro.ts, workrave.ts   executable entry points
 *   <bar>/scripts/lib/*.ts                                   copies of ../lib
 *
 * Each <bar>/ folder can then be copied to ~/.config/<bar>/ and works without
 * `sbs` on PATH. Edit ../lib, never the copies, then run:  npm run vendor
 * `npm test` fails when the copies are out of date.
 */
import { chmod, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");

export const BARS = [
  { dir: "polybar", format: "polybar" },
  { dir: "i3status-rust", format: "i3rs" },
] as const;

export const SOURCES = ["now-playing", "pomodoro", "workrave"] as const;

export function vendorHeader(file: string): string {
  return `// GENERATED from contrib/statusbars/lib/${file} by tools/vendor.ts. Do not edit; run \`npm run vendor\`.\n`;
}

export function entryScript(source: string, format: string, bar: string): string {
  return `#!/usr/bin/env node
// ${bar}: ${source} in ${format} format. GENERATED by tools/vendor.ts.
//   ${source}.ts [--follow] [--interval SECONDS] | ${source}.ts <action> | ${source}.ts click <button>
import { main } from "./lib/entry.ts";

await main(${JSON.stringify(source)}, ${JSON.stringify(format)}, import.meta.dirname);
`;
}

/** Every generated file: path relative to statusbars/ → contents. */
export async function generated(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  const lib = (await readdir(join(root, "lib"))).filter((f) => f.endsWith(".ts")).sort();
  for (const bar of BARS) {
    for (const f of lib) {
      files.set(join(bar.dir, "scripts", "lib", f), vendorHeader(f) + (await readFile(join(root, "lib", f), "utf8")));
    }
    for (const s of SOURCES) files.set(join(bar.dir, "scripts", `${s}.ts`), entryScript(s, bar.format, bar.dir));
    // Keeps the scripts ES modules once the folder is copied out of this repo.
    files.set(join(bar.dir, "scripts", "package.json"), `{ "type": "module", "engines": { "node": ">=26" } }\n`);
  }
  return files;
}

if (import.meta.main) {
  for (const bar of BARS) await rm(join(root, bar.dir, "scripts"), { recursive: true, force: true });
  for (const [rel, content] of await generated()) {
    const path = join(root, rel);
    await mkdir(join(path, ".."), { recursive: true });
    await writeFile(path, content);
    if (rel.endsWith(".ts") && !rel.includes("/lib/")) await chmod(path, 0o755);
    console.log(`wrote ${rel}`);
  }
}
